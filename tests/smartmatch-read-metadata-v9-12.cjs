 assert.equal(old.read(loaded,PDFLib).payload,null,'the prior export verifier gets precisely the reported missing-project-data result');
 console.log('PASS real PDF save/load: '+json.length+' JSON characters; old reader fails, new indirect UTF-16 reader retains Swedish OCR, emoji, checks and time');
 const little=PDFHexString.of('FFFE'+Buffer.from(json,'utf16le').toString('hex'));
 assert.deepEqual(reader.parse(little),payload);
 const edge={text:'a'.repeat(8180)+'😀ÅÄÖ\n'.repeat(12)};
 assert.deepEqual(reader.parse(PDFHexString.fromText(JSON.stringify(edge))),edge);

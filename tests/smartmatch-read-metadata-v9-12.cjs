 assert.deepEqual(reader.parse({decodeText(){return '{"svenska":"övrigt"}';}}),{svenska:'övrigt'});
 assert.throws(()=>reader.parse(PDFHexString.of('FEFF007B00ZG')),/hexadecimal/);
